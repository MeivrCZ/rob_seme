"""Viser viewer of the task scene: the shared SceneViewer and an interactive viewer.

Usage:
    From the repo root::

        uv run Prokop/view_models.py            # then open http://localhost:8080

Scene parts, each can be shown or hidden in the "Scene" panel:

* Robot: the CRS93 with its adapter (models/crs93.urdf).
* Hoop: a separate model (its magnetic mount is not rigid), drawn on the adapter
  at the nominal mount placement.HOOP_MOUNT.
* Base + puzzle D: the puzzle seated in the groove of the ArUco base, on its foam
  on the turntable.
* Turntable: draggable with a gizmo, spinning from the "Turntable" panel.
* Cage + camera: the static work cell of cell.py.
* Model gallery: all static models in a row outside the cage (hidden by default).

The grid is the table surface, the green rectangle the work area seen by the
camera. The interactive viewer (main) moves the robot with joint sliders; the
simulated robot (simulation.CRS93Sim) drives the same SceneViewer from scripts.
"""

from __future__ import annotations

import argparse
import threading
import time
from dataclasses import dataclass, field
from typing import Callable

import numpy as np
import viser
import yourdfpy
from cell import CAMERA_T, cell_meshes
from ctu_crs import CRS93
from placement import (HOOP_MOUNT, MODELS, TABLE_Z, TASK_PUZZLE, WORK_AREA_XY,
                       Placement, TaskScene, load_urdf)
from viser.extras import ViserUrdf

ROBOT = "crs93"  # generated by tools/robodk2urdf.py
SPACING = 0.2  # m between neighbouring models in the gallery row
ROW_X = 1.1  # m, distance of the gallery row in front of the robot (outside the cage)
# s per revolution of the turntable at its slowest speed, the same both ways
# (measured 2026-10-21, docs/MEASUREMENTS.md)
SPIN_PERIOD = 28.0
SPIN_FPS = 30.0  # turntable animation rate
# Initial placement: turntable in front of the robot, base centred on it.
INITIAL_PLACEMENT = Placement(np.array([0.45, 0.0]), np.zeros(2), 0.0)
FRAME_AXES = 0.03  # m, length of the link frame axes
ROBOT_FRAME_AXES = 0.12  # m, longer: robot frames lie inside the link bodies


@dataclass
class Part:
    """A toggleable part of the scene.

    Attributes:
        roots: Root scene nodes (hidden together).
        vis: URDF visualisations (visual / collision meshes switched together).
        frames: Link frame axes (switched together).
    """

    roots: list[viser.SceneNodeHandle] = field(default_factory=list)
    vis: list[ViserUrdf] = field(default_factory=list)
    frames: list[viser.FrameHandle] = field(default_factory=list)


def urdf_vis(server: viser.ViserServer, urdf: yourdfpy.URDF,
             root: str) -> ViserUrdf:
    """Adds the visual and collision meshes of a URDF to the scene.

    The collision meshes start hidden (viser shows them by default and, coinciding
    with the visual ones, they z-fight) and are drawn translucent red.

    Args:
        server: The Viser server.
        urdf: The model.
        root: Scene node name to attach the model to.

    Returns:
        The Viser URDF visualisation.
    """
    vis = ViserUrdf(server, urdf, root_node_name=root, load_collision_meshes=True,
                    collision_mesh_color_override=(1.0, 0.2, 0.2, 0.5))
    vis.show_collision = False
    return vis


def wxyz(T: np.ndarray) -> np.ndarray:
    """Converts the rotation of a 4x4 transform to a Viser quaternion.

    Args:
        T: Homogeneous transform.

    Returns:
        Quaternion (w, x, y, z).
    """
    return viser.transforms.SO3.from_matrix(T[:3, :3]).wxyz


def add_link_frames(server: viser.ViserServer, root: str, urdf: yourdfpy.URDF,
                    axes: float = FRAME_AXES) -> dict[str, viser.FrameHandle]:
    """Adds hidden axes at every link frame of a URDF in its current configuration.

    Includes helper frames such as hoop_center; see update_link_frames for moving
    models.

    Args:
        server: The Viser server.
        root: Scene node name of the model.
        urdf: The model.
        axes: Axis length [m].

    Returns:
        The frame handles by link name.
    """
    frames = {}
    for link in urdf.link_map:
        T = urdf.get_transform(link, urdf.base_link)
        frames[link] = server.scene.add_frame(
            f"{root}/frames/{link}", wxyz=wxyz(T), position=T[:3, 3],
            axes_length=axes, axes_radius=axes / 30, visible=False)
    return frames


def update_link_frames(frames: dict[str, viser.FrameHandle],
                       urdf: yourdfpy.URDF) -> None:
    """Moves link frame axes to the current configuration of their URDF.

    Args:
        frames: Frame handles by link name, from add_link_frames.
        urdf: The model, already updated to the new configuration.
    """
    for link, frame in frames.items():
        T = urdf.get_transform(link, urdf.base_link)
        frame.wxyz, frame.position = wxyz(T), T[:3, 3]


def add_robot(server: viser.ViserServer) -> tuple[Part, yourdfpy.URDF, ViserUrdf,
                                                  dict[str, viser.FrameHandle]]:
    """Adds the robot model.

    Args:
        server: The Viser server.

    Returns:
        The scene part, the URDF, its visualisation and its link frames.
    """
    urdf = load_urdf(MODELS / f"{ROBOT}.urdf")
    root = server.scene.add_frame(f"/{ROBOT}", show_axes=False)
    vis = urdf_vis(server, urdf, f"/{ROBOT}")
    frames = add_link_frames(server, f"/{ROBOT}", urdf, ROBOT_FRAME_AXES)
    return Part([root], [vis], list(frames.values())), urdf, vis, frames


def add_hoop(server: viser.ViserServer) -> tuple[Part, viser.FrameHandle]:
    """Adds the hoop model (placed on the adapter by SceneViewer.show_q).

    Args:
        server: The Viser server.

    Returns:
        The scene part and the root frame to move the hoop with.
    """
    urdf = load_urdf(MODELS / "hoop.urdf")
    root = server.scene.add_frame("/hoop", show_axes=False)
    vis = urdf_vis(server, urdf, "/hoop")
    frames = add_link_frames(server, "/hoop", urdf)
    return Part([root], [vis], list(frames.values())), root


def add_task(server: viser.ViserServer, task: TaskScene
             ) -> tuple[Part, Part, viser.TransformControlsHandle, viser.FrameHandle,
                        viser.FrameHandle]:
    """Adds the turntable and the base with the puzzle seated in its groove.

    The turntable hangs under a gizmo draggable in xy; the base sits on the
    rotating turntable top, the puzzle origin at the base's puzzle_mount.

    Args:
        server: The Viser server.
        task: The task models.

    Returns:
        The turntable part, the base + puzzle part, the gizmo, the (rotating)
        turntable top frame and the base frame.
    """
    gizmo = server.scene.add_transform_controls(
        "/turntable", scale=0.15, active_axes=(True, True, False),
        disable_rotations=True)
    table = server.scene.add_frame("/turntable/model", show_axes=False)
    turntable = Part([table], [urdf_vis(server, task.turntable, "/turntable/model")],
                     list(add_link_frames(server, "/turntable/model",
                                          task.turntable).values()))
    top = server.scene.add_frame("/turntable/top", position=task.T_top[:3, 3],
                                 show_axes=False)
    base_root = server.scene.add_frame("/turntable/top/base", show_axes=False)
    T = task.T_mount
    server.scene.add_frame("/turntable/top/base/puzzle", position=T[:3, 3],
                           wxyz=wxyz(T), show_axes=False)
    vis = [urdf_vis(server, task.base, "/turntable/top/base"),
           urdf_vis(server, task.puzzle, "/turntable/top/base/puzzle")]
    frames = [*add_link_frames(server, "/turntable/top/base", task.base).values(),
              *add_link_frames(server, "/turntable/top/base/puzzle",
                               task.puzzle).values()]
    return turntable, Part([base_root], vis, frames), gizmo, top, base_root


def add_cell(server: viser.ViserServer) -> Part:
    """Adds the static work cell of cell.py.

    Cage walls translucent; camera rail, its post and the camera grey. The
    camera frame (z = optical axis) is added among the link frames.

    Args:
        server: The Viser server.

    Returns:
        The scene part.
    """
    root = server.scene.add_frame("/cell", show_axes=False)
    for name, mesh in cell_meshes().items():
        wall = name.startswith("cage")
        server.scene.add_mesh_simple(
            f"/cell/{name}", mesh.vertices, mesh.faces,
            color=(0.75, 0.85, 0.9) if wall else (0.35, 0.35, 0.38),
            opacity=0.15 if wall else 1.0)
    frame = server.scene.add_frame(
        "/cell/camera_frame", wxyz=wxyz(CAMERA_T), position=CAMERA_T[:3, 3],
        axes_length=FRAME_AXES, axes_radius=FRAME_AXES / 30, visible=False)
    return Part([root], [], [frame])


def add_gallery(server: viser.ViserServer) -> Part:
    """Adds all static models (not the robot) in a labelled row on the table.

    Args:
        server: The Viser server.

    Returns:
        The scene part.
    """
    statics = [(p, load_urdf(p)) for p in sorted(MODELS.glob("*.urdf"))]
    statics = [(p, u) for p, u in statics if u.num_actuated_joints == 0]
    part = Part()
    y0 = -SPACING * (len(statics) - 1) / 2
    for i, (path, urdf) in enumerate(statics):
        root = f"/gallery/{path.stem}"
        z = TABLE_Z - urdf.scene.bounds[0, 2]  # lowest point on the table
        part.roots.append(server.scene.add_frame(
            root, position=(ROW_X, y0 + i * SPACING, z), show_axes=False))
        server.scene.add_label(f"{root}/label", path.stem, position=(0.0, 0.0, -0.02))
        part.vis.append(urdf_vis(server, urdf, root))
        part.frames += add_link_frames(server, root, urdf).values()
    return part


class SceneViewer:
    """Viser server with the task scene and its "Scene", "Display", "Turntable" panels.

    Shared by the interactive viewer (main) and the simulated robot
    (simulation.CRS93Sim), which add their own robot GUI and drive show_q / show.
    The turntable angle is a function of the time given by the clock, so that the
    simulation's robot and turntable share one clock.

    Attributes:
        clock: Time source [s] of the turntable spin.
        server: The Viser server.
        task: The task models (TaskScene).
        robot_urdf: The robot model, kept in the configuration shown.
        robot_vis: Its visualisation.
        placement: The current placement of the turntable and base (after
            add_turntable_gui).
    """

    def __init__(self, port: int = 8080,
                 clock: Callable[[], float] = time.monotonic) -> None:
        """Starts the server and builds the scene.

        Args:
            port: Port of the Viser server.
            clock: Time source [s] for the turntable spin.
        """
        self.clock = clock
        # Turntable spin: angle(t) = angle_ref + omega * (t - t_ref), rebased
        # whenever the spin settings change.
        self._spin_lock = threading.Lock()
        self._t_ref, self._angle_ref, self._omega = clock(), 0.0, 0.0
        server = self.server = viser.ViserServer(port=port)
        server.scene.set_up_direction("+z")
        server.initial_camera.position = (1.3, -1.1, 1.0)
        server.initial_camera.look_at = (0.25, 0.0, 0.35)
        server.scene.add_grid("/grid", width=2.6, height=2.6, cell_size=0.05,
                              plane="xy", position=(0.0, 0.0, TABLE_Z))
        (x0, x1), (y0, y1) = WORK_AREA_XY
        server.scene.add_box("/work_area", color=(0.3, 0.7, 0.3),
                             dimensions=(x1 - x0, y1 - y0, 0.001), opacity=0.35,
                             position=((x0 + x1) / 2, (y0 + y1) / 2, TABLE_Z + 0.0005))

        self.task = TaskScene()
        robot_part, self.robot_urdf, self.robot_vis, self.robot_frames = \
            add_robot(server)
        hoop_part, self.hoop_root = add_hoop(server)
        turntable_part, base_part, self.gizmo, self.top, self.base_root = \
            add_task(server, self.task)
        parts = {
            "Robot": robot_part,
            "Hoop": hoop_part,
            f"Base + {TASK_PUZZLE.replace('_', ' ')}": base_part,
            "Turntable": turntable_part,
            "Cage + camera": add_cell(server),
            "Model gallery": add_gallery(server),
        }

        # --- GUI: scene parts ---
        with server.gui.add_folder("Scene"):
            part_boxes = {name: server.gui.add_checkbox(name, name != "Model gallery")
                          for name in parts}

        def apply_visibility(_=None) -> None:
            for name, part in parts.items():
                for root in part.roots:
                    root.visible = part_boxes[name].value
                for vis in part.vis:
                    vis.show_visual = show_visual.value
                    vis.show_collision = show_collision.value
                for frame in part.frames:
                    frame.visible = show_frames.value

        # --- GUI: display ---
        with server.gui.add_folder("Display"):
            show_visual = server.gui.add_checkbox("Visual meshes", True)
            show_collision = server.gui.add_checkbox("Collision meshes", False)
            show_frames = server.gui.add_checkbox("Link frames", False)
        for box in [*part_boxes.values(), show_visual, show_collision, show_frames]:
            box.on_update(apply_visibility)
        apply_visibility()

    def show_q(self, q: np.ndarray) -> None:
        """Shows the robot, with the hoop on its adapter, in a configuration.

        Sent as one atomic update: separate messages let the browser draw frames
        in which the hoop lags behind the arm.

        Args:
            q: Joint configuration [rad].
        """
        with self.server.atomic():
            self._update_robot(q)

    def show(self, t: float, q: np.ndarray | None = None) -> None:
        """Shows the whole scene at one instant, atomically.

        Args:
            t: Time on the clock [s] (turntable angle).
            q: Joint configuration [rad]; None keeps the robot as it is.
        """
        with self.server.atomic():
            if q is not None:
                self._update_robot(q)
            a = self.turntable_angle(t)
            self.top.wxyz = (np.cos(a / 2), 0.0, 0.0, np.sin(a / 2))

    def _update_robot(self, q: np.ndarray) -> None:
        """Moves the robot model, its link frames and the hoop to @q."""
        self.robot_vis.update_cfg(q)
        update_link_frames(self.robot_frames, self.robot_urdf)
        T = (self.robot_urdf.get_transform("adapter_front", self.robot_urdf.base_link)
             @ HOOP_MOUNT)
        self.hoop_root.wxyz, self.hoop_root.position = wxyz(T), T[:3, 3]

    def turntable_angle(self, t: float) -> float:
        """Rotation of the turntable top.

        Args:
            t: Time on the clock [s], not before the last change of the spin.

        Returns:
            The angle [rad], counter-clockwise from above positive.
        """
        with self._spin_lock:
            return self._angle_ref + self._omega * (t - self._t_ref)

    def set_spin(self, omega: float) -> None:
        """Spins the turntable from now on.

        Args:
            omega: Angular speed [rad/s], counter-clockwise from above positive;
                0 stops it.
        """
        t = self.clock()
        angle = self.turntable_angle(t) % (2 * np.pi)
        with self._spin_lock:
            self._t_ref, self._angle_ref, self._omega = t, angle, omega

    def add_turntable_gui(self, animate: bool = True) -> None:
        """Adds the "Turntable" panel: random placements and spinning.

        Call it after the robot GUI, so that the panels stay in the order Scene,
        Display, robot, Turntable.

        Args:
            animate: Show the spinning turntable from a thread of its own; False
                if the owner renders the scene (show) itself.
        """
        server, task = self.server, self.task
        with server.gui.add_folder("Turntable"):
            random_btn = server.gui.add_button("Random puzzle placement")
            viable_btn = server.gui.add_button(
                "Random viable placement",
                hint="Turntable centre in the work area seen by the camera (green)")
            info = server.gui.add_markdown("")
            spin = server.gui.add_checkbox("Spin", False)
            direction = server.gui.add_dropdown(
                "Direction", ["counter-clockwise (from above)", "clockwise (from above)"])
            period = server.gui.add_number("Period [s/rev]", SPIN_PERIOD, min=1.0,
                                           step=0.1, hint="measured: 28.0 s at the slowest speed")
        rng = np.random.default_rng()

        def show_placement(p: Placement) -> None:
            self.placement = p
            T = p.turntable_T()
            self.gizmo.position = T[:3, 3]
            T = p.base_T_top()
            self.base_root.wxyz, self.base_root.position = wxyz(T), T[:3, 3]
            info.content = (
                f"turntable xy: {np.array2string(p.turntable_xy, precision=3)} m  \n"
                f"base on turntable: {np.array2string(p.base_xy, precision=3)} m, "
                f"{np.rad2deg(p.base_yaw):.0f} deg  \n"
                f"tip-over margin: {1000 * task.stability_margin(p):.1f} mm  \n"
                f"clearance to robot (home, spinning): "
                f"{1000 * task.clearance_to_robot(p):.0f} mm")

        @random_btn.on_click
        def _(_) -> None:
            show_placement(task.random_placement(rng))

        @viable_btn.on_click
        def _(_) -> None:
            show_placement(task.random_placement(rng, WORK_AREA_XY))

        @self.gizmo.on_update
        def _(_) -> None:  # dragged by hand: keep the base, move the turntable
            show_placement(Placement(np.array(self.gizmo.position[:2]),
                                     self.placement.base_xy, self.placement.base_yaw))

        show_placement(INITIAL_PLACEMENT)

        def update_spin(_=None) -> None:
            sign = 1.0 if direction.value.startswith("counter") else -1.0
            self.set_spin(sign * 2 * np.pi / period.value if spin.value else 0.0)

        for control in (spin, direction, period):
            control.on_update(update_spin)

        def spin_loop() -> None:
            """Show the turntable top (with the base and puzzle) while it spins."""
            while True:
                time.sleep(1 / SPIN_FPS)
                if self._omega != 0.0:
                    self.show(self.clock())

        if animate:
            threading.Thread(target=spin_loop, daemon=True).start()


def main() -> None:
    """Runs the interactive viewer: joint sliders, flange position, turntable."""
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--port", type=int, default=8080)
    args = parser.parse_args()

    viewer = SceneViewer(args.port)
    server = viewer.server

    # --- GUI: robot joints and flange position ---
    robot = CRS93(tty_dev=None)
    sliders = []
    with server.gui.add_folder("CRS joints [rad]"):
        for joint, (lo, hi) in viewer.robot_vis.get_actuated_joint_limits().items():
            lo = -np.pi if lo is None else lo
            hi = np.pi if hi is None else hi
            sliders.append(server.gui.add_slider(
                joint, min=lo, max=hi, step=1e-3, initial_value=0.0))
        reset = server.gui.add_button("Zero pose")
        home = server.gui.add_button("Home pose (ctu_crs q_home)")
    with server.gui.add_folder("CRS flange"):
        flange_text = server.gui.add_text("xyz [m]", "", disabled=True)

    def set_q(q: np.ndarray, sync_sliders: bool = True) -> None:
        """Show configuration @q and sync the GUI. Programmatic slider updates fire
        on_update with event.client None, which on_slider ignores."""
        viewer.show_q(q)
        T = robot.fk(q)  # == URDF flange
        flange_text.value = np.array2string(T[:3, 3], precision=3, suppress_small=True,
                                            floatmode="fixed")
        if sync_sliders:
            for s, qi in zip(sliders, q):
                s.value = float(qi)

    def on_slider(event: viser.GuiEvent) -> None:
        if event.client is not None:
            set_q(np.array([s.value for s in sliders]), sync_sliders=False)

    for s in sliders:
        s.on_update(on_slider)

    @reset.on_click
    def _(_) -> None:
        set_q(np.zeros(6))

    @home.on_click
    def _(_) -> None:
        set_q(robot.q_home)

    set_q(np.zeros(6))

    # --- GUI: turntable placement and spinning ---
    viewer.add_turntable_gui()

    print(f"Open http://localhost:{server.get_port()} (Ctrl+C to quit)")
    try:
        while True:
            time.sleep(1.0)
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
